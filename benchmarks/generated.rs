//! Project-generated MMR fixtures shared by runtime and optional oracle tools.

const SIGNATURE: [u8; 8] = [0x97, 0x4a, 0x42, 0x32, 0x0d, 0x0a, 0x1a, 0x0a];

pub fn all_white_mmr_document(width: u32, height: u32) -> Vec<u8> {
    mmr_document(width, height, 1, false)
}

pub fn mmr_document(width: u32, height: u32, pages: u8, alternating: bool) -> Vec<u8> {
    assert!(pages > 0);
    assert!(!alternating || width % 2 == 0);
    let mut page = Vec::new();
    page.extend_from_slice(&width.to_be_bytes());
    page.extend_from_slice(&height.to_be_bytes());
    page.extend_from_slice(&[0; 8]);
    page.extend_from_slice(&[0x40, 0, 0]);
    let mut generic = page[..16].to_vec();
    generic.extend_from_slice(&[0, 1]);
    if alternating {
        let mut bits = Vec::new();
        let mut bit_count = 0_usize;
        for _ in 0..height {
            for _ in 0..width / 2 {
                for bit in b"001000111010" {
                    if bit_count % 8 == 0 {
                        bits.push(0);
                    }
                    if *bit == b'1' {
                        *bits.last_mut().expect("generated byte") |= 0x80 >> (bit_count % 8);
                    }
                    bit_count += 1;
                }
            }
        }
        generic.extend_from_slice(&bits);
    } else {
        generic.extend(std::iter::repeat_n(
            0xff,
            usize::try_from(height.div_ceil(8)).expect("generated height"),
        ));
        if height % 8 != 0 {
            *generic.last_mut().expect("generated byte") = 0xff << (8 - height % 8);
        }
    }
    let mut input = SIGNATURE.to_vec();
    input.push(1);
    input.extend_from_slice(&u32::from(pages).to_be_bytes());
    let mut number = 0;
    for page_number in 1..=pages {
        append_segment(&mut input, number, 48, page_number, &page);
        append_segment(&mut input, number + 1, 38, page_number, &generic);
        append_segment(&mut input, number + 2, 49, page_number, &[]);
        number += 3;
    }
    append_segment(&mut input, number, 51, 0, &[]);
    input
}

fn append_segment(output: &mut Vec<u8>, number: u32, kind: u8, page: u8, data: &[u8]) {
    output.extend_from_slice(&number.to_be_bytes());
    output.extend_from_slice(&[kind, 0, page]);
    output.extend_from_slice(
        &u32::try_from(data.len())
            .expect("generated size")
            .to_be_bytes(),
    );
    output.extend_from_slice(data);
}
